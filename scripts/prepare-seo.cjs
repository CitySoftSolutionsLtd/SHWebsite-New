// Run after editing the public booking roster or adding a page.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, name), 'utf8');
const escape = value => String(value).replace(/[&<>"']/g, ch => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
})[ch]);
const json = data => JSON.stringify(data).replace(/</g, '\\u003c');
const check = process.argv.includes('--check');
function save(name, content) {
  const target = path.join(root, name);
  if (fs.existsSync(target) && read(name) === content) return;
  if (check) throw new Error('Regenerate ' + name + ' with node scripts/prepare-seo.cjs');
  fs.writeFileSync(target, content);
}
const config = { window: {} };
vm.runInNewContext(read('js/bookings-config.js'), config);
const people = config.window.SH_BOOKINGS.staff.filter(p => p.published && p.name && !/^REPLACE_/i.test(p.name));
const template = read('profile.html');
const origin = new URL(template.match(/rel="canonical" href="([^"]+)"/)[1]).origin;
const marker = '<!-- Generated by scripts/prepare-seo.cjs from the public staff roster. -->';
const expected = new Set();
for (const person of people) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(person.slug)) throw new Error('Invalid public staff slug');
  const file = 'profile-' + person.slug + '.html';
  if (expected.has(file)) throw new Error('Duplicate staff slug ' + person.slug);
  expected.add(file);
  const url = origin + '/' + file;
  const title = person.name + ' | SH Elevate Tax Inc.';
  const description = person.title + ' at SH Elevate Tax Inc. Read ' + person.name + '’s profile and book a consultation.';
  const portrait = person.photo && /^images\/[\w./-]+\.(?:jpe?g|png|webp)$/i.test(person.photo) ? person.photo : null;
  const image = origin + '/' + (portrait || 'images/og-image.jpg');
  const schema = {
    '@context':'https://schema.org', '@type':'ProfilePage', '@id':url+'#webpage', url, name:title,
    isPartOf:{'@id':origin+'/#website'},
    mainEntity:{'@type':'Person','@id':url+'#person',name:person.name,jobTitle:person.title,description:person.bio,
      url,image,worksFor:{'@id':origin+'/#organization'}}
  };
  const breadcrumb = { '@context':'https://schema.org','@type':'BreadcrumbList',
    itemListElement: [['Home',origin+'/'],['Team',origin+'/team.html'],[person.name,url]].map(([name,item],i)=>({'@type':'ListItem',position:i+1,name,item})) };
  const metadata = {description,'og:title':title,'og:description':description,'og:url':url,'og:type':'profile',
    'og:image':image,'og:image:alt':portrait?person.name:'SH Elevate Tax Inc.',
    'twitter:title':title,'twitter:description':description,'twitter:image':image,'twitter:image:alt':portrait?person.name:'SH Elevate Tax Inc.'};
  let html = template.replace('<html ',marker+'\n<html ')
    .replace(/<title>[^<]*<\/title>/,()=>'<title>'+escape(title)+'</title>')
    .replace(/(<link rel="canonical" href=")[^"]+/,(_,prefix)=>prefix+escape(url))
    .replace(/<meta (?:name|property)="([^"]+)" content="[^"]*"\s*\/>/g,(tag,key)=>{
      if (/^og:image:(width|height|type)$/.test(key)) return '';
      return Object.hasOwn(metadata,key)?tag.replace(/content="[^"]*"/,()=>'content="'+escape(metadata[key])+'"'):tag;
    })
    .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/,
      ()=>'<script type="application/ld+json">'+json(breadcrumb)+'</script>\n<script type="application/ld+json">'+json(schema)+'</script>')
    .replace('<body ', '<body data-profile-slug="'+person.slug+'" ')
    .replace('id="profile-crumb">Profile<','id="profile-crumb">'+escape(person.name)+'<')
    .replace(/<div id="profile-root">[^\n]*<\/div>/,()=>'<div id="profile-root"><article class="profile-card"><h1 class="profile-name">'+escape(person.name)+'</h1><p class="rm-title">'+escape(person.title)+'</p><p class="rm-bio">'+escape(person.bio || '')+'</p><a href="team.html#appointments">Book an appointment</a></article></div>');
  save(file,html);
}
for (const file of fs.readdirSync(root).filter(n=>/^profile-.*\.html$/.test(n))) {
  if (expected.has(file) || !read(file).includes(marker)) continue;
  if (check) throw new Error('Stale generated profile ' + file);
  fs.unlinkSync(path.join(root,file));
}
const urls = [];
for (const file of fs.readdirSync(root).filter(n=>n.endsWith('.html'))) {
  const html = read(file);
  if (/<meta name="robots" content="[^"]*noindex/i.test(html)) continue;
  const canonical = html.match(/<link rel="canonical" href="([^"]+)"/)?.[1];
  if (canonical !== new URL(file==='index.html' ? '/' : file,origin).href) throw new Error('Invalid canonical on '+file);
  urls.push(canonical);
}
urls.sort();
save('sitemap.xml','<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+
  urls.map(url=>'  <url><loc>'+escape(url)+'</loc></url>').join('\n')+'\n</urlset>\n');
